def source_snapshot(source):
    return {str(path.relative_to(source)): path.read_bytes() for path in source.rglob("*") if path.is_file()}


def test_actual_pinned_files_match_recorded_upstream_hashes(patcher, source):
    for name, expected in patcher.PINNED_SHA256.items():
        assert hashlib.sha256((source / name).read_bytes()).hexdigest() == expected


def test_fresh_overlay_keeps_original_and_other_library_unchanged(patcher, source, tmp_path):
    before = source_snapshot(source)
    target = tmp_path / "src-x11fix-1"
    result = patcher.prepare_overlay(source, target)
    assert result["reused"] is False
    assert result["patch_id"] == "voicepeak-xputpixel-1"
    assert source_snapshot(source) == before
    assert not (target / ".git").exists()
    assert (target / "x64lib/lib-test.so.1").read_bytes() == b"minimal other copied library"
    assert (target / "x64lib/lib-test.so").is_symlink()
    manifest = json.loads((target / patcher.MANIFEST_NAME).read_text())
    assert manifest["protected_entries"]["x64lib/lib-test.so.1"]["sha256"]
    assert manifest["build_generated_exclusions"] == ["src/wrapped/generated", "src/emu/x64printer.c", "src/git_head.h"]
    for name, expected in result["patched_sha256"].items():
        assert hashlib.sha256((target / name).read_bytes()).hexdigest() == expected
    header = (target / "src/wrapped/wrappedlibx11_private.h").read_text()
    assert "GOM(XPutPixel, iFEpiiL)" in header
    assert "//GO(XPutPixel," not in header


def test_repeated_overlay_reuses_unchanged_target(patcher, source, tmp_path):
    target = tmp_path / "candidate"
    first = patcher.prepare_overlay(source, target)
    before = source_snapshot(target)
    second = patcher.prepare_overlay(source, target)
    assert second["reused"] is True
    assert second["patched_sha256"] == first["patched_sha256"]
    assert source_snapshot(target) == before


def test_upstream_generated_build_outputs_do_not_block_retry(patcher, source, tmp_path):
    target = tmp_path / "candidate"
    patcher.prepare_overlay(source, target)
    (target / "src/wrapped/generated/wrapper.c").write_text("regenerated by upstream CMake\n")
    (target / "src/wrapped/generated/newtypes.h").write_text("upstream generated native types\n")
    (target / "src/emu/x64printer.c").write_text("regenerated upstream ABI printer\n")
    (target / "src/git_head.h").write_text('#define GITREV ""\n')
    assert patcher.prepare_overlay(source, target)["reused"] is True
    assert (target / "src/wrapped/generated/wrapper.c").read_text() == "regenerated by upstream CMake\n"


