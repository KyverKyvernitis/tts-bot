def test_native_pixel_dispatch_restores_callback_bridge(patcher, tmp_path):
    compiler = shutil.which("gcc")
    if compiler is None:
        pytest.skip("native C compiler unavailable")
    harness = r'''#include <stdint.h>
#include <assert.h>
#define EXPORT
typedef struct { int unused; } x64emu_t;
typedef struct _XImage XImage;
struct _XImage {
    int32_t (*put_pixel)(void*, int32_t, int32_t, uintptr_t);
    uintptr_t stored;
};
static int bridges, unbridges, calls;
static int32_t native_callback(void* image, int32_t x, int32_t y, uintptr_t pixel)
{
    assert(x == 2 && y == 3);
    ((XImage*)image)->stored = pixel;
    ++calls;
    return 17;
}
static int32_t emulated_bridge(void* image, int32_t x, int32_t y, uintptr_t pixel)
{
    assert(!"native Xlib must not dispatch directly to the emulated bridge");
    return -1;
}
static void UnbridgeImageFunc(x64emu_t* emu, XImage* image)
{
    assert(image->put_pixel == emulated_bridge);
    image->put_pixel = native_callback;
    ++unbridges;
}
static void BridgeImageFunc(x64emu_t* emu, XImage* image)
{
    assert(image->put_pixel == native_callback);
    image->put_pixel = emulated_bridge;
    ++bridges;
}
static int32_t native_XPutPixel(void* image, int32_t x, int32_t y, uintptr_t pixel)
{
    return ((XImage*)image)->put_pixel(image, x, y, pixel);
}
static struct { int32_t (*XPutPixel)(void*, int32_t, int32_t, uintptr_t); } api = { native_XPutPixel };
static __typeof__(api)* my = &api;
'''
    harness += patcher.PATCH_BODY.decode()
    harness += r'''int main(void)
{
    XImage image = { emulated_bridge, 0 };
    x64emu_t emu = {0};
    uintptr_t pixel = UINT64_C(0xf123456789abcdef);
    assert(my_XPutPixel(&emu, &image, 2, 3, pixel) == 17);
    assert(image.put_pixel == emulated_bridge);
    assert(image.stored == pixel);
    assert(calls == 1 && bridges == 1 && unbridges == 1);
    return 0;
}
'''
    code = tmp_path / "pixel-dispatch.c"
    binary = tmp_path / "pixel-dispatch"
    code.write_text(harness)
    built = subprocess.run([compiler, "-std=gnu11", "-Wall", "-Wextra", "-Wno-unused-parameter", "-Werror", str(code), "-o", str(binary)], text=True, capture_output=True, timeout=15)
    assert built.returncode == 0, built.stderr
    checked = subprocess.run([str(binary)], text=True, capture_output=True, timeout=5)
    assert checked.returncode == 0, checked.stderr


