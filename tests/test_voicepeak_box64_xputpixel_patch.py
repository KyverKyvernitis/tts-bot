def test_copy_failure_does_not_publish_partial_target(patcher, source, tmp_path, monkeypatch):
    target = tmp_path / "candidate"

    def fail_copy(original, staging, **kwargs):
        staging.mkdir()
        (staging / "partial-file").write_text("incomplete")
        raise OSError("disk full")

    monkeypatch.setattr(patcher.shutil, "copytree", fail_copy)
    with pytest.raises(OSError, match="disk full"):
        patcher.prepare_overlay(source, target)
    assert not target.exists()
    assert not list(tmp_path.glob(".voicepeak-xputpixel-*"))


def test_concurrent_destination_is_not_overwritten(patcher, source, tmp_path, monkeypatch):
    target = tmp_path / "candidate"
    publish = patcher._publish_new

    def create_destination(staging, destination):
        destination.mkdir()
        publish(staging, destination)

    monkeypatch.setattr(patcher, "_publish_new", create_destination)
    with pytest.raises(patcher.OverlayError, match="apareceu"):
        patcher.prepare_overlay(source, target)
    assert target.is_dir() and list(target.iterdir()) == []
    assert not list(tmp_path.glob(".voicepeak-xputpixel-*"))


