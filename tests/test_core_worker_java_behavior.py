"""Execute real Java helper classes on a JVM with small Android boundary fakes.

Set CORE_WORKER_JSON_JAR to org.json:json:20240303 and, without javac,
CORE_WORKER_ECJ_JAR to Eclipse ECJ. No network or downloads happen in tests.
"""
from __future__ import annotations

import os
from pathlib import Path
import shutil
import subprocess
import io
import tarfile

import pytest

ROOT = Path(__file__).resolve().parents[1]
JAVA = ROOT / "android/core-worker-app/app/src/main/java/dev/core/worker"


@pytest.fixture(scope="session")
def java_harness(tmp_path_factory):
    java = shutil.which("java")
    javac = shutil.which("javac")
    ecj = os.environ.get("CORE_WORKER_ECJ_JAR", "")
    json_jar = os.environ.get("CORE_WORKER_JSON_JAR", "")
    if not java or not Path(json_jar).is_file() or not (javac or Path(ecj).is_file()):
        message = "Java harness requires java, javac (or CORE_WORKER_ECJ_JAR) and CORE_WORKER_JSON_JAR"
        if os.environ.get("CORE_WORKER_REQUIRE_JAVA_TESTS") == "1":
            pytest.fail(message)
        pytest.skip(message)
    output = tmp_path_factory.mktemp("core-worker-java")
    classes = ["CoreWorkerRuntimeIdentity", "CoreWorkerAutoEnrollment", "CoreWorkerSocketListener",
               "CoreWorkerHttpTransport", "CoreWorkerUpdateArtifacts", "CoreWorkerBackgroundIo",
               "LocalNativeTtsHttpServer", "CoreWorkerDirectHttpServer",
               "CoreLinuxRootfsFilesystem", "CoreLinuxRootfsTarExtractor", "CoreWorkerAtomicTextFiles",
               "CoreWorkerApkToolchainFilesystem", "CoreWorkerProcessRunner", "CoreWorkerNativeCalls"]
    sources = [str(JAVA / (name + ".java")) for name in classes]
    sources += [str(p) for directory in [ROOT / "tests/java_support", ROOT / "tests/java_harness"]
                for p in sorted(directory.rglob("*.java"))]
    command = [javac, "--release", "17"] if javac else [java, "-jar", ecj, "-17", "-nowarn"]
    compile_run = subprocess.run(command + ["-encoding", "UTF-8", "-cp", json_jar, "-d", str(output), *sources],
                                 capture_output=True, text=True, timeout=90)
    assert compile_run.returncode == 0, compile_run.stdout + compile_run.stderr
    return [java, "-ea", "-cp", os.pathsep.join([str(output), json_jar]), "dev.core.worker.WorkerHarness"]


