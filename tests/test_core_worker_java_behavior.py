@pytest.mark.parametrize("format", [tarfile.USTAR_FORMAT, tarfile.PAX_FORMAT, tarfile.GNU_FORMAT])
def test_java_tar_interoperability(java_harness, tmp_path, format):
    archive, target = tmp_path / "rootfs.tar.gz", tmp_path / "staging"
    target.mkdir()
    # Generated by Python's standard TAR writer, independently of our Java
    # fixture builder. Include legitimate whitespace and relative symlink names.
    names = ["usr/share/empty", "usr/share/ spaced "]
    if format != tarfile.USTAR_FORMAT:
        names.append("usr/share/á-" + "long-name-" * 20 + " ")
    with tarfile.open(archive, "w:gz", format=format) as tar:
        for name in names:
            content = b"" if name.endswith("empty") else "conteúdo".encode()
            entry = tarfile.TarInfo(name)
            entry.size = len(content)
            tar.addfile(entry, io.BytesIO(content))
        link = tarfile.TarInfo("usr/share/link")
        link.type = tarfile.SYMTYPE
        link.linkname = " spaced "
        tar.addfile(link)
    result = subprocess.run([*java_harness, "tar_external", str(archive), str(target)],
                            capture_output=True, text=True, timeout=10)
    assert result.returncode == 0, result.stdout + result.stderr
    for name in names:
        assert (target / name).read_bytes() == (b"" if name.endswith("empty") else "conteúdo".encode())
    assert os.readlink(target / "usr/share/link") == " spaced "
    assert (target / "usr/share/link").read_bytes() == "conteúdo".encode()
